def esc(s):
    return s.replace('\\', '\\\\').replace("'", "\\'")

def build_block(pairs, idx):
    lines = []
    for p in pairs:
        key = p[0]
        val = p[idx]
        lines.append(f"  '{esc(key)}': '{esc(val)}',")
    return '\n'.join(lines)

def append_to(path, block):
    with io.open(path, 'r', encoding='utf-8') as f:
        content = f.read()
    # Insert before the last "};"
    idx = content.rfind('};')
    if idx < 0:
        raise SystemExit(f"Could not find closing brace in {path}")
    # Ensure a preceding newline
    new = content[:idx] + '\n  // --- retrofitted marketplace/drivers/fleet page keys ---\n' + block + '\n' + content[idx:]
    with io.open(path, 'w', encoding='utf-8', newline='\n') as f:
        f.write(new)

append_to(EN_PATH, build_block(PAIRS, 1))
append_to(HI_PATH, build_block(PAIRS, 2))
print(f"Added {len(PAIRS)} keys to EN and HI.")
