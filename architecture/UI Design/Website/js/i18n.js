(function(){
  function applyLang(lang){
    var dict = window.TS_I18N[lang] || window.TS_I18N.en;
    document.querySelectorAll('[data-i18n]').forEach(function(el){
      var key = el.getAttribute('data-i18n');
      if(dict[key] !== undefined){ el.innerHTML = dict[key]; }
    });
    document.querySelectorAll('[data-i18n-placeholder]').forEach(function(el){
      var key = el.getAttribute('data-i18n-placeholder');
      if(dict[key] !== undefined){ el.setAttribute('placeholder', dict[key]); }
    });
    document.documentElement.setAttribute('lang', lang === 'hi' ? 'hi' : 'en');
    document.querySelectorAll('.lang-opt').forEach(function(el){
      el.classList.toggle('active', el.getAttribute('data-lang') === lang);
    });
    try{ localStorage.setItem('ts_lang', lang); }catch(e){}
  }
  window.TS_SET_LANG = applyLang;
  document.addEventListener('DOMContentLoaded', function(){
    var saved = 'en';
    try{ saved = localStorage.getItem('ts_lang') || 'en'; }catch(e){}
    applyLang(saved);
    var sw = document.getElementById('langSwitch');
    if(sw){
      sw.addEventListener('click', function(){
        var current = document.documentElement.getAttribute('lang') === 'hi' ? 'hi' : 'en';
        applyLang(current === 'en' ? 'hi' : 'en');
      });
    }
  });
})();
